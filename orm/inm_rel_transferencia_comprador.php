<?php

namespace gamboamartin\inmuebles\models;

use base\orm\_modelo_parent;
use gamboamartin\errores\errores;
use PDO;
use stdClass;


class inm_rel_transferencia_comprador extends _modelo_parent{
    public function __construct(PDO $link)
    {
        $tabla = 'inm_rel_transferencia_comprador';
        $columnas = array($tabla=>false,'inm_transferencia'=>$tabla,'inm_comprador'=>$tabla,
            'bn_cuenta'=>'inm_transferencia');

        $campos_obligatorios = array();

        $columnas_extra= array();
        $renombres= array();

        $atributos_criticos = array();

        parent::__construct(link: $link, tabla: $tabla, campos_obligatorios: $campos_obligatorios,
            columnas: $columnas, columnas_extra: $columnas_extra, renombres: $renombres,
            atributos_criticos: $atributos_criticos);

        $this->NAMESPACE = __NAMESPACE__;
        $this->etiqueta = 'Relacion transferencia';
    }

    public function alta_bd(array $keys_integra_ds = array('codigo', 'descripcion')): array|stdClass
    {
        if(!isset($this->registro['inm_transferencia_id'])) {
            $registro_transferencia = array();

            $registro_transferencia['monto'] = $this->registro['monto'];
            $registro_transferencia['nombre_beneficiario'] = $this->registro['nombre_beneficiario'];
            $registro_transferencia['bn_cuenta_id'] = $this->registro['bn_cuenta_id'];
            $registro_transferencia['transferencia'] = '';

            if (isset($this->registro['transferencia'])) {
                $registro_transferencia['transferencia'] = $this->registro['transferencia'];
            }

            $r_inm_transferencia = (new inm_transferencia(link: $this->link))->alta_registro(registro: $registro_transferencia);
            if (errores::$error) {
                return $this->error->error(mensaje: 'Error al insertar prospecto', data: $r_inm_transferencia);
            }

            $this->registro['inm_transferencia_id'] = $r_inm_transferencia->registro_id;

            $inm_ubicaciones = (new _inm_comprador())->inm_ubicaciones(
                inm_comprador_id: $this->registro['inm_comprador_id'], link:  $this->link);
            if(errores::$error){
                return $this->error->error(mensaje: 'Error al insertar prospecto', data: $inm_ubicaciones);
            }

            $registro = array();
            $registro['inm_ubicacion_id'] = $inm_ubicaciones[0]['inm_ubicacion_id'];
            $registro['monto'] = $this->registro['monto'];
            $registro['fecha'] = date('Y-m-d');
            $registro['referencia'] = $this->registro['nombre_beneficiario'];
            $registro['inm_concepto_id'] = 19;

            $r_inm_costo = (new inm_costo(link: $this->link))->alta_registro(registro: $registro);
            if (errores::$error) {
                return $this->error->error(mensaje: 'Error al insertar prospecto',data:  $r_inm_costo);
            }

            $registro = array();
            $registro['inm_costo_id'] = $r_inm_costo->registro_id;
            $registro['inm_transferencia_id'] = $r_inm_transferencia->registro_id;
            $r_rel_costo_transferencia = (new inm_rel_costo_transferencia(link: $this->link))->alta_registro(registro: $registro);
            if (errores::$error) {
                return $this->error->error(mensaje: 'Error al insertar prospecto',data:  $r_rel_costo_transferencia);
            }

            unset($this->registro['monto'], $this->registro['nombre_beneficiario'],
                $this->registro['numero_transferencia']);
        }


        if (!isset($this->registro['descripcion'])) {
            $descripcion = $this->registro['inm_comprador_id'];
            $descripcion .= ' ' . $this->registro['inm_transferencia_id'];
            $this->registro['descripcion'] = $descripcion;
        }

        if (!isset($this->registro['codigo'])) {
            $descripcion = $this->registro['inm_comprador_id'];
            $descripcion .= ' ' . $this->registro['inm_transferencia_id'] . rand();
            $this->registro['codigo'] = $descripcion;
        }


        $r_alta_bd = parent::alta_bd(keys_integra_ds: $keys_integra_ds); // TODO: Change the autogenerated stub
        if (errores::$error) {
            return $this->error->error(mensaje: 'Error al insertar prospecto', data: $r_alta_bd);
        }

        return $r_alta_bd;
    }

    public function elimina_bd(int $id): array|stdClass
    {
        $filtro = array();
        $filtro['inm_rel_transferencia_comprador.id'] = $id;
        $r_rel = $this->filtro_and(filtro: $filtro);
        if(errores::$error){
            return $this->error->error(mensaje: 'Error al obtener relacion',data:  $r_rel);
        }

        if($r_rel->n_registros > 0) {
            $modelo_inm_doc = new inm_rel_doc_transferencia(link: $this->link);

            $filtro = array();
            $filtro['inm_transferencia.id'] = $r_rel->registros[0]['inm_transferencia_id'];
            $r_doc = $modelo_inm_doc->filtro_and(filtro: $filtro);
            if (errores::$error) {
                return $this->error->error(mensaje: 'Error al obtener relacion documento', data: $r_doc);
            }

            if ($r_doc->n_registros > 0) {
                return $this->error->error(mensaje: 'Error al existe un documento de poliza transferencia',
                    data: $r_doc);
            }
        }

        $r_elimina_bd = parent::elimina_bd(id:  $id);
        if(errores::$error){
            return $this->error->error(mensaje: 'Error al eliminar descripcion',data:  $r_elimina_bd);
        }

        if($r_rel->n_registros > 0) {
            $r_elimina = (new inm_transferencia(link: $this->link))->elimina_bd(
                id: $r_rel->registros[0]['inm_transferencia_id']);
            if (errores::$error) {
                return $this->error->error(mensaje: 'Error al obtener relacion', data: $r_elimina);
            }
        }

        return $r_elimina_bd;
    }
}