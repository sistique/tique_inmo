    final public function data_pdf(int $registro_id): array|stdClass
    {
        if($registro_id<=0){
            return $this->error->error(mensaje: 'Error al registro_id debe ser mayor a 0',
                data: $registro_id);
        }

        $filtro['inm_cheque.id'] = $registro_id;
        $inm_cheque = (new inm_rel_cheque_ubicacion(link: $this->link))->filtro_and(filtro: $filtro);
        if (errores::$error) {
            return $this->error->error(mensaje: 'Error al obtener cheque', data: $inm_cheque);
        }


        $data = new stdClass();
        $data->inm_cheque = $inm_cheque->registros[0];

        return $data;
    }
}