<?php

namespace gamboamartin\inmuebles\models;

use base\orm\_modelo_parent;
use gamboamartin\errores\errores;
use PDO;
use stdClass;

class inm_efectivo extends _modelo_parent{
    public function __construct(PDO $link)
    {
        $tabla = 'inm_efectivo';
        $columnas = array($tabla=>false,'inm_ubicacion'=>$tabla);

        $columnas_extra= array();
        $renombres= array();


        parent::__construct(link: $link, tabla: $tabla, columnas: $columnas, columnas_extra: $columnas_extra,
            renombres: $renombres);

        $this->NAMESPACE = __NAMESPACE__;
        $this->etiqueta = 'efectivo';
    }

    public function alta_bd(array $keys_integra_ds = array('codigo', 'descripcion')): array|stdClass
    {
        if(!isset($this->registro['descripcion'])){
            $descripcion = $this->registro['inm_ubicacion_id'];
            $descripcion .= ' '.$this->registro['numero_efectivo'];
            $this->registro['descripcion'] = $descripcion;
        }

        if(!isset($this->registro['codigo'])){
            $descripcion = $this->registro['inm_ubicacion_id'];
            $descripcion .= ' '.$this->registro['numero_efectivo'] . rand();
            $this->registro['codigo'] = $descripcion;
        }

        $r_alta_bd = parent::alta_bd(keys_integra_ds: $keys_integra_ds); // TODO: Change the autogenerated stub
        if(errores::$error){
            return $this->error->error(mensaje: 'Error al insertar prospecto',data:  $r_alta_bd);
        }

        $registro = array();
        $registro['inm_ubicacion_id'] = $this->registro['inm_ubicacion_id'];
        $registro['inm_concepto_id'] = 19;
        $registro['monto'] = $this->registro['monto'];
        $registro['fecha'] = date('Y-m-d');
        $registro['referencia'] = $this->registro['nombre_beneficiario'];
        $r_inm_costo = (new inm_costo(link: $this->link))->alta_registro(
            registro: $registro);
        if (errores::$error) {
            return $this->error->error(mensaje: 'Error al insertar prospecto',data:  $r_inm_costo);
        }

        return $r_alta_bd;
    }

    public function modifica_bd(array $registro, int $id, bool $reactiva = false, array $keys_integra_ds = array('codigo', 'descripcion')): array|stdClass
    {
        $r_modifica_bd = parent::modifica_bd(registro: $registro,id:  $id,reactiva:  $reactiva,
            keys_integra_ds:  $keys_integra_ds);
        if(errores::$error){
            return $this->error->error(mensaje: 'Error al modificar descripcion',data:  $r_modifica_bd);
        }


        return $r_modifica_bd;
    }

}